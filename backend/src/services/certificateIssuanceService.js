const crypto = require('crypto');
const Certificate = require('../models/Certificate');
const AuditLog = require('../models/AuditLog');
const ipfsService = require('../config/ipfs');
const EncryptionService = require('./encryption/encryptionService');
const { issueCertificate } = require('./fabricClient');
const { generateDigitalCredentialPdf } = require('./digitalCredentialService');

const hashBuffer = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

const commonInstitutions = {
    'the university of zambia': 'UNZA',
    'university of zambia': 'UNZA',
    'copperbelt university': 'CBU',
    'the copperbelt university': 'CBU',
    'mulungushi university': 'MU',
    'kapasa makasa university': 'KMU',
    'kmu': 'KMU',
    'evelyn hone college': 'EHC',
    'zambia centre for accountancy studies': 'ZCAS',
    'zcas university': 'ZCAS',
    'national institute for public administration': 'NIPA',
    'nipa': 'NIPA',
    'examinations council of zambia': 'ECZ',
    'ecz': 'ECZ'
};

const getInstitutionPrefix = (name) => {
    if (!name) return '';
    const clean = name.toLowerCase().trim();
    if (commonInstitutions[clean]) {
        return commonInstitutions[clean];
    }
    const words = name.toUpperCase().split(/[\s-]+/).filter(w => w && !['THE', 'OF', 'AND', 'FOR', 'TO', 'CO', 'LTD'].includes(w));
    if (words.length === 0) return '';
    if (words.length === 1) {
        return words[0].slice(0, 4);
    }
    return words.map(w => w[0]).join('');
};

const generateDeterministicId = (institutionName, certificationNumber) => {
    if (!institutionName || !certificationNumber) return '';
    const prefix = getInstitutionPrefix(institutionName);
    const cleanCert = certificationNumber.trim().replace(/[\s/]+/g, '-');
    return prefix ? `${prefix}-${cleanCert}` : cleanCert;
};

const generateCertificateId = (studentId, documentHash) => {
    const nonce = crypto.randomBytes(16).toString('hex');
    return crypto
        .createHash('sha256')
        .update(`${studentId}-${documentHash}-${Date.now()}-${nonce}`)
        .digest('hex');
};

const issueCertificateRecord = async ({
    studentId,
    courseName,
    metadata = {},
    certificateFile,
    fileName,
    fileType,
    issuedByUser,
    studentUserId,
    requestMeta = {},
    // New structured layouts
    issuerDetails,
    studentDetails,
    academicRecord,
    documentEvidence
}) => {
    const resolvedStudentId = studentDetails?.studentNumber || studentId || 'unknown';
    const resolvedCourseName = academicRecord?.program || courseName || 'unknown';
    const resolvedStudentName = studentDetails?.fullName || metadata.studentName || '';

    // 1. Resolve or generate deterministic certificate identifier
    let certificateId;
    if (issuerDetails && issuerDetails.certificationNumber) {
        certificateId = generateDeterministicId(issuerDetails.institutionName, issuerDetails.certificationNumber);
    } else {
        const prefix = getInstitutionPrefix(issuerDetails?.institutionName || 'UNZA') || 'CERT';
        certificateId = `${prefix}-${resolvedStudentId}-${Date.now().toString().slice(-6)}`;
    }

    let fileBuffer;
    let resolvedFileName = fileName;
    let resolvedFileType = fileType;
    let isAutoGenerated = false;

    // 2. If certificateFile is supplied, use it; otherwise auto-generate official Digital Credential Diploma PDF
    if (certificateFile) {
        fileBuffer = Buffer.from(certificateFile, 'base64');
        resolvedFileName = fileName || `certificate-${certificateId}.pdf`;
        resolvedFileType = fileType || 'application/pdf';
    } else {
        isAutoGenerated = true;
        const baseUrl = process.env.FRONTEND_URL || process.env.APP_URL || 'http://localhost:3000';
        const verificationUrl = `${baseUrl}/verify/${certificateId}`;

        const certTemplate = {
            certificateId,
            studentId: resolvedStudentId,
            courseName: resolvedCourseName,
            issuerDetails: issuerDetails || {
                institutionType: 'University',
                institutionName: 'BlockD3 University',
                certificationNumber: certificateId
            },
            studentDetails: studentDetails || {
                studentNumber: resolvedStudentId,
                fullName: resolvedStudentName,
                nationalId: ''
            },
            academicRecord: academicRecord || {
                program: resolvedCourseName,
                programSpecification: metadata.major || '',
                awardClassification: metadata.grade || (metadata.cgpa ? String(metadata.cgpa) : ''),
                graduationDate: metadata.graduationDate || new Date().toISOString()
            },
            metadata
        };

        fileBuffer = await generateDigitalCredentialPdf(certTemplate, verificationUrl);
        certificateFile = fileBuffer.toString('base64');
        resolvedFileName = `digital-credential-${certificateId}.pdf`;
        resolvedFileType = 'application/pdf';
    }

    // 3. Compute deterministic SHA-256 hash of original unencrypted document
    const documentHash = hashBuffer(fileBuffer);

    // 4. Encrypt document using AES-256 before decentralized storage
    const recipientKeyPair = EncryptionService.generateUserKeyPair(`certificate:${certificateId}`);
    const encryptedCertificate = await EncryptionService.encryptCertificate(
        fileBuffer,
        recipientKeyPair.publicKey
    );

    // 4. Upload encrypted document payload to IPFS (confidential storage)
    let ipfsHash = null;
    try {
        const encryptedBuffer = Buffer.from(encryptedCertificate.encryptedCertificate.data, 'hex');
        ipfsHash = await ipfsService.uploadWithRetry(encryptedBuffer);
        console.log('Encrypted document uploaded to IPFS:', ipfsHash);
    } catch (ipfsError) {
        console.warn('IPFS upload fallback:', ipfsError.message);
    }

    // Build the dynamic payload matching new Zambian structure
    const fabricPayload = {
        id: certificateId,
        certificateId,
        documentHash,
        issuerDetails: issuerDetails || {
            institutionType: 'University',
            institutionName: 'BlockD3 University',
            certificationNumber: certificateId
        },
        studentDetails: studentDetails || {
            studentNumber: resolvedStudentId,
            fullName: resolvedStudentName,
            nationalId: ''
        },
        academicRecord: academicRecord || {
            program: resolvedCourseName,
            programSpecification: metadata.major || '',
            awardClassification: metadata.grade || (metadata.cgpa ? String(metadata.cgpa) : ''),
            graduationDate: metadata.graduationDate || new Date().toISOString()
        },
        documentEvidence: {
            fileHash: documentHash,
            storageURI: ipfsHash ? `ipfs://${ipfsHash}` : (documentEvidence?.storageURI || '')
        },
        metadata: metadata || {}
    };

    console.log('Recording certificate on Hyperledger Fabric...');
    const fabricResult = await issueCertificate(fabricPayload);

    if (!fabricResult.ok) {
        const error = new Error(fabricResult.error || 'Fabric issuance failed');
        error.statusCode = 502;
        throw error;
    }

    const certificate = new Certificate({
        certificateId,
        studentId: resolvedStudentId,
        courseName: resolvedCourseName,
        documentHash,
        ipfsHash,
        issuedBy: issuedByUser._id,
        studentUser: studentUserId || null,
        transactionHash: null,
        // Zambian structured layout fields
        issuerDetails: fabricPayload.issuerDetails,
        studentDetails: fabricPayload.studentDetails,
        academicRecord: fabricPayload.academicRecord,
        documentEvidence: fabricPayload.documentEvidence,
        bridge_status: 'pending',

        encryption: {
            encryptedDocumentHash: encryptedCertificate.documentHash,
            encryptedAESKey: encryptedCertificate.encryptedAESKey,
            aesEncryption: {
                iv: encryptedCertificate.encryptedCertificate.iv,
                authTag: encryptedCertificate.encryptedCertificate.authTag,
                algorithm: encryptedCertificate.encryptedCertificate.algorithm
            },
            digitalSignature: encryptedCertificate.digitalSignature,
            issuerKeys: {
                publicKey: encryptedCertificate.issuerKeys.publicKey,
                keyPairId: encryptedCertificate.issuerKeys.keyPairId
            },
            encryptionVersion: encryptedCertificate.encryptionMetadata.encryptionVersion,
            encryptedAt: encryptedCertificate.encryptionMetadata.timestamp
        },
        verificationProof: {
            proofHash: documentHash,
            algorithm: 'SHA-256'
        },
        authorizedViewers: [
            {
                userId: issuedByUser._id,
                publicKey: recipientKeyPair.publicKey,
                authorizedBy: issuedByUser._id
            },
            ...(studentUserId && studentUserId.toString() !== issuedByUser._id.toString() ? [{
                userId: studentUserId,
                publicKey: recipientKeyPair.publicKey,
                authorizedBy: issuedByUser._id
            }] : [])
        ],
        metadata: {
            ...metadata,
            studentName: resolvedStudentName,
            graduationDate: fabricPayload.academicRecord.graduationDate,
            program: fabricPayload.academicRecord.program,
            major: fabricPayload.academicRecord.programSpecification,
            originalFileName: resolvedFileName || null,
            originalFileType: resolvedFileType || null,
            encryptedCertificate: encryptedCertificate.encryptedCertificate,
            certificateFile,
            downloadedFileHash: documentHash,
            recognizedFileHashes: [documentHash],
            isAutoGenerated
        }
    });

    await certificate.save();

    await AuditLog.create({
        actor: issuedByUser?._id,
        actorEmail: issuedByUser?.email,
        action: 'fabric.certificate.issue',
        target: certificate.certificateId,
        metadata: {
            transactionHash: null,
            studentId: certificate.studentId,
            source: requestMeta.source || 'manual'
        },
        ipAddress: requestMeta.ipAddress,
        userAgent: requestMeta.userAgent
    });

    return certificate;
};

module.exports = {
    issueCertificateRecord
};
